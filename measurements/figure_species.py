#!/usr/bin/env python3
"""Generate Figure 2's pgfplots body -- values AND confidence intervals -- from the stamped reports."""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(REPO / "model"), str(REPO / "eval"), str(REPO / "target" / "py")]

from scrm_eval import registry as R  # noqa: E402

P = R.PROJ

#: THE arm this figure plots, declared ONCE here and read from the registry rather than spelled
#: out below. It is the same seed every table reports.
ARM = R.FLAGSHIP

COLUMNS = (
    (1.0, "human cell line", "sc_mixology_5cl", "bar"),
    (1.9, "human", "pbmc_10k_v3", "line"),
    (2.6, "fly", "fly_antenna", "line"),
    (3.3, "rat", "2500_wistar_rat_pbmcs_singleplex_3p_gem_x", "line"),
    (4.0, "macaque", "2500_rhesus_monkey_pbmcs_singleplex_3p_gem_x", "line"),
    (4.7, "mouse", "tm_10X_P7_2", "line"),
)

STYLE = (
    ("count_scanpy", r"\texttt{scanpy}", "black", "square", "2.6pt",
     "solid, fill=white, draw=black, line width=0.7pt", "dashed"),
    ("geneformer", "Geneformer", "blue!60!black", "triangle*", "2pt", "", ""),
    ("scgpt", "scGPT", "teal!75!black", "diamond*", "2pt", "", ""),
    ("uce", "UCE", "violet!75!black", "pentagon*", "2pt", "", ""),
    (ARM, "scrm", "red!75!black", "*", "1.6pt", "", ""),
    ("scvi_pretrained", "scVI", "orange!85!black", "x", "2pt", "", ""),
    ("genejepa", "GeneJEPA", "brown!70!black", "otimes", "2pt", "fill=white", ""),
)

FIELD = "acc_mean_standardised_ADDITION"

Z = 1.959963984540054


def wilson(p: float, n: int, z: float = Z) -> tuple[float, float]:
    """The Wilson score interval for a proportion `p` over `n` observations."""
    if n <= 0:
        return (p, p)
    denom = 1.0 + z * z / n
    centre = (p + z * z / (2 * n)) / denom
    half = z / denom * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (max(0.0, centre - half), min(1.0, centre + half))


def read_column(dataset: str) -> tuple[dict[str, float], int]:
    """`{model: accuracy}` and the scored cell count, from one protocol-B report."""
    f = P / "eval_reports" / "uce" / f"b_logreg.{dataset}.json"
    if not f.is_file():
        raise FileNotFoundError(f"{f} is not on disk; the figure cannot be generated without it")
    d = json.loads(f.read_text())
    vals = {m: e[FIELD] for m, e in d["results"].items() if e.get(FIELD) is not None}
    return vals, int(d["n_cells"])


def points() -> dict[str, list[tuple[float, float, float, float, int]]]:
    """`model -> [(x, value, err_minus, err_plus, n_cells)]`, one entry per column it appears in."""
    out: dict[str, list] = {m: [] for m, *_ in STYLE}
    for x, _label, dataset, _kind in COLUMNS:
        vals, n = read_column(dataset)
        missing = [m for m, *_ in STYLE if m not in vals]
        if missing:
            raise KeyError(
                f"{dataset}: the report has no {FIELD} for {missing}. The figure would silently "
                "drop a model, so this stops instead."
            )
        for m, *_ in STYLE:
            v = vals[m]
            lo, hi = wilson(v, n)
            out[m].append((x, v, v - lo, hi - v, n))
    return out


def emit() -> str:
    pts = points()
    bar_x = COLUMNS[0][0]
    lines = []
    lines.append("% GENERATED by measurements/figure_species.py -- do not edit by hand.")
    lines.append(f"% Values are {FIELD} from eval_reports/uce/b_logreg.<dataset>.json.")
    lines.append("% Error bars are 95% Wilson intervals on the accuracy over the scored cells;")
    lines.append("% they are MARGINAL, so overlap does not establish that two models agree --")
    lines.append("% see measurements/paired_significance.py for the paired tests.")
    lines.append("")
    lines.append("% --- the task boundary ---")
    lines.append(r"\addplot[black!22, dashed, line width=0.5pt, forget plot, mark=none]")
    lines.append(r"  coordinates {(1.5,0.70) (1.5,1.015)};")
    lines.append("")
    lines.append("% --- column 1, cell line identity: one bar per model, with its interval ---")
    shift = -21
    for (m, _leg, colour, mark, size, mopt, _dash) in STYLE:
        x, v, em, ep, _n = pts[m][0]
        assert x == bar_x
        fill = "black!42" if colour == "black" else f"{colour}!70"
        lines.append(
            f"\\addplot[ybar, bar width=5pt, bar shift={shift}pt, fill={fill}, draw=none, "
            f"forget plot] coordinates {{({x:g},{v:.4f})}};")
        opts = mopt if mopt else f"draw={colour}, fill={colour}"
        lines.append(
            f"\\addplot[xshift={shift}pt, only marks, {colour}, mark={mark}, mark size={size}, "
            f"mark options={{{opts}}}, forget plot, error bars/.cd, y dir=both, y explicit] "
            f"coordinates {{({x:g},{v:.4f}) += (0,{ep:.4f}) -= (0,{em:.4f})}};")
        shift += 7
    lines.append("")
    lines.append("% --- columns 2-6, cell type annotation: one line per model, with intervals ---")
    for (m, legend, colour, mark, size, mopt, dash) in STYLE:
        style = f"mark={mark}, {colour}"
        if dash:
            style += f", {dash}"
        style += f", mark size={size}"
        if mopt:
            style += f",\n         mark options={{{mopt}}}"
        coords = " ".join(
            f"({x:g},{v:.4f}) += (0,{ep:.4f}) -= (0,{em:.4f})"
            for x, v, em, ep, _n in pts[m][1:])
        lines.append(f"\\addplot[{style},\n         error bars/.cd, y dir=both, y explicit]")
        lines.append(f"  coordinates {{{coords}}};")
        lines.append(f"\\addlegendentry{{{legend}}}")
        lines.append("")
    return "\n".join(lines)



def macros() -> str:
    """The cell-line panel's numbers as macros, because the main text states them in prose.

    It said scRM reads $0.985$ against a count range of $0.865$ to $0.999$; the figure derives
    the same quantities, and the literals had already drifted from it. COUNT_KEYS is every
    plotted model that is not ours, so the range cannot silently start including our own row.
    """
    vals, n = read_column(COLUMNS[0][2])
    count_keys = [m for m, *_ in STYLE if m != ARM]
    counts = [vals[m] for m in count_keys if m in vals]
    ours = vals.get(ARM)
    # Every quantity sec:identity states in prose, derived from the same protocol-B reports as the
    # figure.
    ann = [(lab, ds) for _x, lab, ds, _k in COLUMNS[1:]]
    gaps, extra = [], []
    for lab, ds in ann:
        v, _ = read_column(ds)
        cs = [v[m] for m in count_keys if m in v]
        if ARM in v and cs:
            gaps.append(max(cs) - v[ARM])
    hv, _ = read_column("pbmc_10k_v3")
    fv, _ = read_column("fly_antenna")
    SHORT = {"scvi_pretrained": "Scvi", "scgpt": "Scgpt", "geneformer": "Geneformer",
             "uce": "Uce", "genejepa": "Genejepa", ARM: "Scrm"}
    for m, tag in SHORT.items():
        if m in hv and m in fv:
            extra.append(("SpeciesFlyDelta" + tag, f"${abs(hv[m] - fv[m]):.3f}$"))
            extra.append(("SpeciesFlyDir" + tag, "falls" if hv[m] > fv[m] else "gains"))
    mv, _ = read_column("tm_10X_P7_2")
    mcs = [mv[m] for m in count_keys if m in mv]
    if mcs and ARM in mv:
        extra += [("SpeciesMouseCountLo", f"${min(mcs):.3f}$"),
                  ("SpeciesMouseCountHi", f"${max(mcs):.3f}$"),
                  ("SpeciesMouseScrm", f"${mv[ARM]:.3f}$")]
    if ours is not None and counts:
        extra.append(("SpeciesCellLineGap", f"${max(counts) - ours:.3f}$"))
    if gaps:
        extra += [("SpeciesAnnotGapLo", f"${min(gaps):.3f}$"),
                  ("SpeciesAnnotGapHi", f"${max(gaps):.3f}$")]
    if "genejepa" in hv:
        extra.append(("SpeciesGenejepaHuman", f"${hv['genejepa']:.3f}$"))

    _missing = "\\" + R.TEX_NS + "Missing{species}"
    out = ["% GENERATED by measurements/figure_species.py -- do not edit by hand.",
           f"% The cell-line panel of {COLUMNS[0][2]}, {n:,} cells, {FIELD}.",
           "\\newcommand{\\" + R.TEX_NS + "SpeciesScrm}{"
           + (f"${ours:.3f}$" if ours is not None else _missing) + "}",
           "\\newcommand{\\" + R.TEX_NS + "SpeciesCountLo}{"
           + (f"${min(counts):.3f}$" if counts else _missing) + "}",
           "\\newcommand{\\" + R.TEX_NS + "SpeciesCountHi}{"
           + (f"${max(counts):.3f}$" if counts else _missing) + "}"]
    out += ["\\newcommand{\\" + R.TEX_NS + k + "}{" + v + "}" for k, v in extra]
    return "\n".join(out)

def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-o", "--out", type=Path, help="write here instead of stdout")
    ap.add_argument("--table", action="store_true",
                    help="print the values and intervals as text, for checking against the paper")
    a = ap.parse_args(argv)

    if a.table:
        pts = points()
        print(f"{'model':28s} " + " ".join(f"{c[1][:9]:>18s}" for c in COLUMNS))
        for m, *_ in STYLE:
            cells = " ".join(f"{v:.4f} -{em:.4f}/+{ep:.4f}" for _x, v, em, ep, _n in pts[m])
            print(f"{m:28s} {cells}")
        print("\nn_cells per column: " +
              ", ".join(f"{c[1]}={read_column(c[2])[1]}" for c in COLUMNS))
        return 0

    body = emit()
    if a.out:
        a.out.parent.mkdir(parents=True, exist_ok=True)
        tmp = a.out.with_suffix(a.out.suffix + ".tmp")
        tmp.write_text(body + "\n")
        tmp.replace(a.out)
        print(f"wrote {a.out}")
        # The prose's copies of these numbers live in the main text, so they are derived too.
        mac = a.out.with_name("species_n.tex")
        tmpm = mac.with_suffix(".tex.tmp")
        tmpm.write_text(macros() + "\n")
        tmpm.replace(mac)
        print(f"wrote {mac}")
    else:
        print(body)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
